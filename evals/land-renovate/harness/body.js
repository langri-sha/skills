export const REBASE_UNCHECKED =
  '- [ ] <!-- rebase-check -->If you want to rebase/retry this PR, check this box'
export const REBASE_CHECKED = REBASE_UNCHECKED.replace('[ ]', '[x]')

const releaseNotes = (bytes) => {
  const entries = []
  let size = 0

  for (let index = 1; size < bytes; index++) {
    const entry = [
      '<details>',
      `<summary>example/package (example-${index})</summary>`,
      '',
      `### [\`v1.${index}.0\`](https://example.invalid/releases/v1.${index}.0)`,
      '',
      `- fix: handle malformed input in parser stage ${index}`,
      `- feat: add option \`strict${index}\` to the resolver`,
      `- chore: refresh generated fixtures for run ${index}`,
      '',
      '</details>',
      '',
    ].join('\n')

    entries.push(entry)
    size += entry.length
  }

  return entries.join('\n')
}

export const renovateBody = ({ title, update, bytes = 0 }) => {
  const table = update
    ? [
        '| Package | Change | Age | Confidence |',
        '|---|---|---|---|',
        `| [${update.package}](https://example.invalid/${update.package}) | \`${update.from}\` -> \`${update.to}\` | ![age](https://example.invalid/age) | ![confidence](https://example.invalid/confidence) |`,
      ].join('\n')
    : `Maintenance update: ${title}`

  return [
    'This PR contains the following updates:',
    '',
    table,
    '',
    '---',
    '',
    '### Release Notes',
    '',
    bytes > 0 ? releaseNotes(bytes) : '_No release notes._',
    '',
    '---',
    '',
    '### Configuration',
    '',
    '📅 **Schedule**: Branch creation - At any time (no schedule defined), Automerge - At any time (no schedule defined).',
    '',
    '🚦 **Automerge**: Disabled by config. Please merge this manually once you are satisfied.',
    '',
    '♻ **Rebasing**: Whenever PR becomes conflicted, or you tick the rebase/retry checkbox.',
    '',
    '🔕 **Ignore**: Close this PR and you won’t be reminded about this update again.',
    '',
    '---',
    '',
    REBASE_UNCHECKED,
    '',
    '---',
    '',
    'This PR was generated by [Mend Renovate](https://mend.io/renovate/). View the [repository job log](https://example.invalid/job).',
    '',
  ].join('\n')
}
